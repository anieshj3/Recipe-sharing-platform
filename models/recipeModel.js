const mongoose = require("mongoose");

// ==================================================
// RECIPE SCHEMA
// ==================================================

const recipeSchema = new mongoose.Schema(
    {
        // ==================================================
        // RECIPE NAME
        // ==================================================

        recipeName: {
            type: String,
            required: true,
            trim: true
        },

        // ==================================================
        // CATEGORY
        // ==================================================

        category: {
            type: String,
            required: true,
            trim: true
        },

        // ==================================================
        // COOKING TIME
        // ==================================================

        cookingTime: {
            type: Number,
            required: true,
            min: 1
        },

        // ==================================================
        // DIFFICULTY
        // ==================================================

        difficulty: {
            type: String,
            enum: [
                "Easy",
                "Medium",
                "Hard"
            ],
            required: true
        },

        // ==================================================
        // DINING TIME
        // ==================================================

        diningTime: {
            type: String,
            default: "",
            trim: true
        },

        // ==================================================
        // INGREDIENTS
        // ==================================================

        ingredients: {
            type: [String],
            required: true
        },

        // ==================================================
        // PREPARATION STEPS
        // ==================================================

        steps: {
            type: [String],
            required: true
        },

        // ==================================================
        // RECIPE IMAGE URL
        // ==================================================

        image: {
            type: String,
            default: "",
            trim: true
        },

        // ==================================================
        // RECIPE OWNER
        // ==================================================

        userId: {
            type: mongoose.Schema.Types.ObjectId,
            ref: "User",
            required: true
        }
    },

    // ==================================================
    // TIMESTAMPS
    // ==================================================

    {
        timestamps: true
    }
);

// ==================================================
// CREATE MODEL
// ==================================================

const Recipe = mongoose.model(
    "Recipe",
    recipeSchema
);

// ==================================================
// EXPORT
// ==================================================

module.exports = Recipe;